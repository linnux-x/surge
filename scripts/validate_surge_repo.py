#!/usr/bin/env python3
"""Repository invariant checks for linnux-x/surge.

This script intentionally uses only the Python standard library so it can run
both locally and inside GitHub Actions without dependency setup.
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

# Ensure scripts/ is on the path
_scripts_dir = str(Path(__file__).resolve().parent)
if _scripts_dir not in sys.path:
    sys.path.insert(0, _scripts_dir)

from rule_validator import (
    validate_rule_file, warn_rule_file, parse_total_header, non_comment_rules,
    ALLOWED_TYPES, OPTION_TOKENS, SUKKAW_MARKER,
)

ROOT = Path(__file__).resolve().parents[1]
RULE_DIR = ROOT / "Rule"
WORKFLOW_DIR = ROOT / ".github" / "workflows"
MAIN_WORKFLOW = WORKFLOW_DIR / "auto-rules.yml"
README = ROOT / "README.md"
MAIN_CONF = ROOT / "Conf" / "Linnux.conf"
MANAGED_CONFIG_HEADER = (
    "#!MANAGED-CONFIG "
    "https://raw.githubusercontent.com/linnux-x/surge/main/Conf/Linnux.conf "
    "interval=86400"
)

# Import shared validator — constants and functions come from rule_validator now


def rel(path: Path) -> str:
    return str(path.relative_to(ROOT))


def extract_process_rule_targets() -> set[str]:
    """Return all expected ruleset filenames from the single source of truth."""
    from sources import ALL_RULESETS
    return ALL_RULESETS.copy()


def extract_workflow_name(text: str) -> str | None:
    match = re.search(r"^name:\s*(.+?)\s*$", text, flags=re.M)
    return match.group(1).strip().strip('"\'') if match else None


def has_schedule_trigger(text: str) -> bool:
    lines = text.splitlines()
    in_on = False
    on_indent = None
    for line in lines:
        if re.match(r"^on:\s*$", line):
            in_on = True
            on_indent = 0
            continue
        if in_on:
            if line and not line.startswith((" ", "\t")) and not line.lstrip().startswith("#"):
                in_on = False
                continue
            if re.match(r"^\s+schedule:\s*$", line):
                return True
    return False


def check_workflow_inventory(errors: list[str]) -> None:
    if not MAIN_WORKFLOW.exists():
        errors.append(f"Missing main workflow: {rel(MAIN_WORKFLOW)}")
        return
    rule_files = {p.name for p in RULE_DIR.glob("*.list")}
    targets = extract_process_rule_targets()
    missing_in_workflow = sorted(rule_files - targets)
    missing_files = sorted(targets - rule_files)
    if missing_in_workflow:
        errors.append("Rule files not generated by main workflow: " + ", ".join(missing_in_workflow))
    if missing_files:
        errors.append("Main workflow targets missing Rule/*.list files: " + ", ".join(missing_files))


def check_workflow_names_and_deprecated_schedule(errors: list[str], warnings: list[str]) -> None:
    names: dict[str, list[Path]] = defaultdict(list)
    for path in sorted(WORKFLOW_DIR.glob("*.yml")):
        text = path.read_text(encoding="utf-8", errors="replace")
        name = extract_workflow_name(text)
        if name:
            names[name].append(path)
        if path.name != MAIN_WORKFLOW.name and has_schedule_trigger(text):
            stale_rule_workflow = (
                path.name == "auto-surge-rules.yml"
                or "process_rule" in text
                or re.search(r"\bRule/[A-Za-z0-9_]+[.]list\b", text)
            )
            if stale_rule_workflow:
                errors.append(f"Deprecated/non-main rule workflow still has schedule trigger: {rel(path)}")
    for name, paths in sorted(names.items()):
        if len(paths) > 1:
            errors.append("Duplicate GitHub Actions workflow name " + repr(name) + ": " + ", ".join(rel(p) for p in paths))
    if not names:
        warnings.append("No workflow names found")


def check_readme_inventory(errors: list[str]) -> None:
    if not README.exists():
        errors.append("README.md is missing")
        return
    text = README.read_text(encoding="utf-8", errors="replace")
    # Match backtick-wrapped filenames
    listed = set(re.findall(r"`([A-Za-z0-9_]+\.list)`", text))
    # Also match rule table rows: | emoji filename.list |
    listed |= set(re.findall(r"^\|\s*[^\s|]+\s+([A-Za-z0-9_]+\.list)\s+\|", text, re.M))
    rule_files = {p.name for p in RULE_DIR.glob("*.list")}
    stale = sorted(listed - rule_files)
    missing = sorted(rule_files - listed)
    if stale:
        errors.append("README mentions non-existent rule files: " + ", ".join(stale))
    if missing:
        errors.append("README omits rule files: " + ", ".join(missing))


def check_rule_files(errors: list[str], warnings: list[str]) -> None:
    for path in sorted(RULE_DIR.glob("*.list")):
        rules = [l for l in path.read_text(encoding="utf-8", errors="replace").splitlines()
                 if l.strip() and not l.strip().startswith("#")]
        total = parse_total_header(path)
        if total is not None and total != len(rules):
            errors.append(f"{rel(path)} TOTAL header {total} ≠ actual {len(rules)}")
        errs = validate_rule_file(rules, path.name)
        for e in errs:
            errors.append(f"{rel(path)} {e}")
        warns = warn_rule_file(rules, path.name)
        for warning in warns:
            warnings.append(f"{rel(path)} {warning}")


def check_source_snapshots(errors: list[str]) -> None:
    """Snapshot records must describe a published ruleset and its current sources.

    A record is optional (rulesets get one on their next generation), but a
    stale one would make --offline rebuild from inputs the generator no longer uses.
    """
    import json
    from sources import RULE_SPECS
    for path in sorted((RULE_DIR / ".sources").glob("*")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            target = data["ruleset"]
            pinned = [(s["label"], s["url"], s["format"]) for s in data["sources"]]
            hashes = [s["sha256"] for s in data["sources"]]
        except (OSError, ValueError, KeyError, TypeError) as exc:
            errors.append(f"{rel(path)} is not a valid snapshot record: {exc}")
            continue
        if path.suffix != ".json" or path.stem + ".list" != target or not (RULE_DIR / target).is_file():
            errors.append(f"{rel(path)} does not match a published ruleset")
        elif target not in RULE_SPECS or pinned != [tuple(s) for s in RULE_SPECS[target][1]]:
            errors.append(f"{rel(path)} sources differ from scripts/sources.py; regenerate {target}")
        elif not all(isinstance(h, str) and re.fullmatch(r"[0-9a-f]{64}", h) for h in hashes):
            errors.append(f"{rel(path)} has a malformed sha256")


def check_managed_config_header(errors: list[str]) -> None:
    """Ensure the main Surge profile remains a managed profile after updates."""
    if not MAIN_CONF.exists():
        errors.append(f"Missing main Surge config: {rel(MAIN_CONF)}")
        return
    lines = MAIN_CONF.read_text(encoding="utf-8", errors="replace").splitlines()
    first_line = lines[0].strip() if lines else ""
    if first_line != MANAGED_CONFIG_HEADER:
        errors.append(
            f"{rel(MAIN_CONF)} first line must be: {MANAGED_CONFIG_HEADER}"
        )


def check_override_manifest(errors: list[str]) -> None:
    """Run the public Manual override contract in-process before publication."""
    from validate_override_manifest import main as validate_overrides
    if validate_overrides() != 0:
        errors.append("Rule/Manual override manifest validation failed")


def main() -> int:
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--ci", action="store_true",
                        help="CI mode: skip workflow-inventory and README-consistency checks")
    args = parser.parse_args()

    errors: list[str] = []
    warnings: list[str] = []

    if not args.ci:
        check_workflow_inventory(errors)
        check_readme_inventory(errors)
    check_workflow_names_and_deprecated_schedule(errors, warnings)
    check_managed_config_header(errors)
    check_override_manifest(errors)
    from audit_rules import check_exclude_coverage
    for finding in check_exclude_coverage():
        errors.append(f"{finding['target']}: {finding['detail']}")
    check_rule_files(errors, warnings)
    check_source_snapshots(errors)
    from validate_dns_module import normalize_text as normalize_dns_module
    from validate_dns_module import validate_text as validate_dns_module
    try:
        dns_module = (ROOT / 'Module/DNS-Mapping.sgmodule').read_text(encoding='utf-8')
        validate_dns_module(dns_module)
        if dns_module != normalize_dns_module(dns_module):
            errors.append('DNS mapping module: must end with exactly one newline; '
                          'run python3 scripts/validate_dns_module.py --normalize')
    except (OSError, ValueError) as exc:
        errors.append(f'DNS mapping module: {exc}')

    if warnings:
        print("WARNINGS:")
        for warning in warnings:
            print(f"- {warning}")
    if errors:
        print("VALIDATION FAILED:")
        for error in errors:
            print(f"- {error}")
        return 1

    print("VALIDATION PASSED")
    print(f"Rule files: {len(list(RULE_DIR.glob('*.list')))}")
    print(f"Main workflow targets: {len(extract_process_rule_targets())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
